def seed_question_bank(db: Session) -> None:
    existing_skills = {skill.name: skill for skill in db.query(Skill).all()}
    for skill_name, description, category in SEED_SKILLS:
        if skill_name not in existing_skills:
            skill = Skill(name=skill_name, description=description, category=category)
            db.add(skill)
            db.flush()
            existing_skills[skill_name] = skill

    for skill_name, questions in QUESTION_BANK.items():
        skill = existing_skills.get(skill_name)
        if skill is None:
            continue
        for question_entry in questions:
            existing_question = (
                db.query(Question)
                .filter(Question.skill_id == skill.id, Question.question_text == question_entry["question_text"])
                .first()
            )
            if existing_question:
                continue
            labelled_options = [
                f"{chr(65 + idx)}. {value}"
                for idx, value in enumerate(question_entry["options"])
            ]
            question = Question(
                skill_id=skill.id,
                question_text=question_entry["question_text"],
                options_json=labelled_options,
                correct_option=question_entry["correct_option"],
                difficulty=question_entry["difficulty"],
                explanation=question_entry["explanation"],
                topic=question_entry["topic"],
            )
            db.add(question)

    db.commit()
